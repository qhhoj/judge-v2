use crate::GENERATOR_VERSION;
use crate::classify::Role;
use crate::model::{Function, Interface, Ret};

pub(crate) fn banner(header: &str) -> String {
    format!(
        "// Generated by qhhoj-judge (interface generator {GENERATOR_VERSION}). Do not edit.\n\
         #include \"{header}\"\n#include \"qhhoj_rpc.hpp\"\n"
    )
}

/// The functions with `role`, in declaration order (`roles` is indexed by `Function::id`, one per function).
pub(crate) fn with_role<'a>(interface: &'a Interface, roles: &[Role], role: Role) -> Vec<&'a Function> {
    assert_eq!(roles.len(), interface.functions.len(), "one role per function");
    let pairs = interface.functions.iter().zip(roles);
    pairs.filter(|(_, found)| **found == role).map(|(function, _)| function).collect()
}

/// `ret name(T qhhoj_a0, ...)`: the definition line of a proxy, matching the header's declaration.
pub(crate) fn signature(function: &Function) -> String {
    let params: Vec<String> =
        function.params.iter().enumerate().map(|(i, p)| p.cpp(&format!("qhhoj_a{i}"))).collect();
    format!("{} {}({})", function.ret.cpp(), function.name, params.join(", "))
}

/// `qhhoj_a0, qhhoj_a1, ...` for a call with the function's arguments.
pub(crate) fn arguments(function: &Function) -> String {
    (0..function.params.len()).map(|i| format!("qhhoj_a{i}")).collect::<Vec<_>>().join(", ")
}

/// A proxy: the definition that sends the call and returns its result. `serve` is `, qhhoj_serve` on the jury.
pub(crate) fn proxy(function: &Function, serve: &str) -> String {
    let mut out = format!("{} {{\n", signature(function));
    out += &format!("  qhhoj::Call qhhoj_call({}{serve});\n", function.id);
    for i in 0..function.params.len() {
        out += &format!("  qhhoj_call.put(qhhoj_a{i});\n");
    }
    out += &proxy_result(function);
    out + "}\n"
}

/// How the proxy's result comes back to its caller.
fn proxy_result(function: &Function) -> String {
    match &function.ret {
        Ret::Void => "  qhhoj_call.done();\n".to_string(),
        Ret::Value(ty) => format!("  return qhhoj_call.result<{} >();\n", ty.cpp()),
        // One copy per object the jury returned, so references to different objects never alias.
        Ret::ConstRef(ty) => format!("  return qhhoj_call.result_cached<{} >();\n", ty.cpp()),
    }
}
